// Script to automate testing the /export endpoint and saving the PDF
const fs = require("fs");
const http = require("http");

const postData = JSON.stringify({
  title: "Automated PDF Test",
  body: "This PDF was generated by an automated script to test the /export endpoint.",
});

const options = {
  hostname: "localhost",
  port: 3000,
  path: "/export",
  method: "POST",
  headers: {
    "Content-Type": "application/json",
    "Content-Length": Buffer.byteLength(postData),
  },
};

const req = http.request(options, (res) => {
  if (res.statusCode !== 200) {
    console.error(`Request failed with status ${res.statusCode}`);
    res.resume();
    return;
  }
  const file = fs.createWriteStream("./samples/automated_export_test.pdf");
  res.pipe(file);
  file.on("finish", () => {
    file.close();
    console.log("PDF saved as automated_export_test.pdf");
  });
});

req.on("error", (e) => {
  console.error(`Problem with request: ${e.message}`);
});

req.write(postData);
req.end();
